#!/usr/bin/env node
// Packs the Lucide icons TradeV uses into public/icons.js (inline SVG, no network at runtime)
// and public/icons.css (empty-state art). Re-run after changing the ICONS list:
//   git clone --depth 1 --filter=blob:none --sparse https://github.com/lucide-icons/lucide /tmp/lucide
//   (cd /tmp/lucide && git sparse-checkout set icons)
//   node scripts/build-icons.js /tmp/lucide
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const ICONS = [
  // navigation
  'chart-candlestick', 'chart-line', 'chart-pie', 'wallet', 'shield-check', 'layout-dashboard', 'users',
  'arrow-left-right', 'receipt-text', 'log-out', 'languages',
  // trading
  'trending-up', 'trending-down', 'chevron-down', 'x', 'check', 'circle-x', 'target', 'shield-exclamation-point',
  'arrow-down-to-line', 'arrow-up-from-line', 'coins', 'percent', 'activity', 'trophy', 'scale', 'landmark',
  'chart-column', 'hand-coins', 'circle-dollar-sign', 'clock',
  // actions & feedback
  'plus', 'user-plus', 'pencil', 'refresh-cw', 'search', 'circle-check', 'circle-exclamation-point', 'info', 'inbox',
  'zap', 'eye', 'sheet', 'layers', 'lock', 'mail', 'user-round', 'settings', 'megaphone', 'server', 'banknote', 'headset', 'sun', 'moon', 'bell', 'send', 'flask-conical', 'rotate-ccw', 'octagon-exclamation-point', 'triangle-exclamation-point', 'trash',
];

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-icons.js <path to lucide checkout>'); process.exit(1); }
const dir = path.join(src, 'icons');
const license = fs.readFileSync(path.join(src, 'LICENSE'), 'utf8').split('\n').slice(0, 3).join(' ').trim();

const inner = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(dir, `${name}.svg`), 'utf8');
  const body = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '').trim();
  if (!body || /<script|on\w+=/i.test(body)) throw new Error(`unexpected content in ${name}.svg`);
  inner[name] = body;
}

const js = `/* Icons: Lucide (https://lucide.dev) — ${license}
   Generated by scripts/build-icons.js — do not edit by hand. */
'use strict';
const ICON_PATHS = ${JSON.stringify(inner, null, 1)};
function icon(name, cls = '') {
  const body = ICON_PATHS[name];
  if (!body) return '';
  return \`<svg class="i \${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${body}</svg>\`;
}
// <i data-icon="name"></i> placeholders in static HTML
function hydrateIcons(root = document) {
  root.querySelectorAll('i[data-icon]').forEach((el) => { el.outerHTML = icon(el.dataset.icon, el.className); });
}
if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => hydrateIcons()); else hydrateIcons();
window.icon = icon;
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.js'), js);

const svgUrl = (name) => `url("data:image/svg+xml;utf8,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='1.5' stroke-linecap='round' stroke-linejoin='round'>${inner[name]}</svg>`)}")`;
const css = `/* Icons: Lucide (https://lucide.dev) — ${license}. Generated by scripts/build-icons.js */
.empty::before { content: ""; display: block; width: 34px; height: 34px; margin: 0 auto 10px; background: currentColor; opacity: .55;
  -webkit-mask: ${svgUrl('inbox')} center / contain no-repeat; mask: ${svgUrl('inbox')} center / contain no-repeat; }
`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.css'), css);
console.log(`packed ${ICONS.length} icons → public/icons.js, public/icons.css`);
